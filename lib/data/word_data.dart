List<String> getRandomWrongOptions(String correctAnswer, int count) {
  final allAnswers = wordList.map((w) => w.answer).toSet().toList();
  allAnswers.remove(correctAnswer);
  allAnswers.shuffle(Random());
  return allAnswers.take(count).toList();
}

List<String> getOptions(String correctAnswer) {
  final wrongs = getRandomWrongOptions(correctAnswer, 3);
  final opts = [...wrongs, correctAnswer]..shuffle(Random());
  return opts;
}

